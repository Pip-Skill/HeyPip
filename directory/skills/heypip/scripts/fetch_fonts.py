#!/usr/bin/env python3
"""Self-host the brand's Google Fonts next to the site, so it looks right in every browser
(no third-party request, works offline, behind blockers and under strict CSP).

Usage:
  python3 fetch_fonts.py <brand.json> <out_dir> [--subsets latin,latin-ext,cyrillic,cyrillic-ext]
  python3 fetch_fonts.py --families "Cormorant Garamond:400,600;Manrope:400,500,600" <out_dir>

Writes <out_dir>/fonts.css and <out_dir>/files/*.woff2. In the page:
  <link rel="preload" href="fonts/files/<display-face>-latin-400-normal.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="fonts/fonts.css">
and remove the fonts.googleapis.com links.

Fonts come from Fontsource (npm), which repackages Google Fonts under their own open licences
(OFL / Apache); each family's LICENSE is copied into <out_dir>/licenses/. Needs `npm` on PATH.
It also reports which families lack a subset you asked for (e.g. Fraunces has no Cyrillic).
"""
import json
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import brandlib as B  # noqa: E402

DEFAULT_SUBSETS = ["latin", "latin-ext", "cyrillic", "cyrillic-ext"]


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def families_from_brand(path):
    brand = B.load(path)
    out = {}
    for fam in brand.get("type", {}).get("families", {}).values():
        n = fam.get("name")
        if not n or fam.get("source", "google") != "google":
            continue
        out.setdefault(n, set()).update(fam.get("weights", [400]))
    return out


def families_from_arg(s):
    out = {}
    for part in s.split(";"):
        if not part.strip():
            continue
        name, _, ws = part.partition(":")
        out[name.strip()] = {int(w) for w in (ws or "400").split(",") if w.strip()}
    return out


def fetch(name, weights, subsets, out, tmp):
    pkg = f"@fontsource/{slug(name)}"
    r = subprocess.run(["npm", "pack", pkg, "--silent"], cwd=tmp, capture_output=True, text=True)
    if r.returncode:
        return f"{name}: not on Fontsource ({pkg}) — keep the Google Fonts link for it"
    tgz = next(Path(tmp).glob(f"fontsource-{slug(name)}-*.tgz"))
    ex = Path(tmp) / slug(name)
    with tarfile.open(tgz) as t:
        t.extractall(ex, filter="data")
    root = ex / "package"
    css_out, have, missing_w = [], set(), []
    for w in sorted(weights):
        f = root / f"{w}.css"
        if not f.exists():
            missing_w.append(w)
            continue
        for block in re.findall(r"/\* .*? \*/\s*@font-face \{.*?\}", f.read_text(), re.S):
            m = re.search(r"/\* (.+?)-(\d+)-normal \*/", block)
            sub = m.group(1)[len(slug(name)) + 1:] if m else ""
            if sub not in subsets:
                continue
            have.add(sub)
            woff2 = re.search(r"url\(\./files/([^)]+\.woff2)\)", block).group(1)
            shutil.copy(root / "files" / woff2, out / "files" / woff2)
            block = re.sub(r"src: [^;]+;", f"src: url(./files/{woff2}) format('woff2');", block)
            css_out.append(block)
    lic = root / "LICENSE"
    if lic.exists():
        shutil.copy(lic, out / "licenses" / f"{slug(name)}.txt")
    notes = []
    lacking = [s for s in subsets if s not in have]
    if lacking:
        notes.append(f"{name}: no {', '.join(lacking)} subset")
    if missing_w:
        notes.append(f"{name}: no static weight {missing_w}")
    return css_out, notes


def main():
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    subsets = DEFAULT_SUBSETS
    if "--subsets" in a:
        i = a.index("--subsets")
        subsets = a[i + 1].split(",")
        del a[i:i + 2]
    if a[0] == "--families":
        fams, out = families_from_arg(a[1]), Path(a[2])
    else:
        fams, out = families_from_brand(a[0]), Path(a[1])
    (out / "files").mkdir(parents=True, exist_ok=True)
    (out / "licenses").mkdir(exist_ok=True)
    css, notes = ["/* Self-hosted fonts — generated by heypip/fetch_fonts.py from Fontsource */"], []
    with tempfile.TemporaryDirectory() as tmp:
        for name, ws in fams.items():
            res = fetch(name, ws, subsets, out, tmp)
            if isinstance(res, str):
                notes.append(res)
                continue
            css += res[0]
            notes += res[1]
    (out / "fonts.css").write_text("\n\n".join(css) + "\n", encoding="utf-8")
    n = len(list((out / "files").glob("*.woff2")))
    print(f"wrote {out}/fonts.css and {n} woff2 files for: {', '.join(fams)}")
    for x in notes:
        print("note:", x)


if __name__ == "__main__":
    main()
