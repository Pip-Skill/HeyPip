#!/usr/bin/env python3
"""brand.json -> tokens.css, tokens.tailwind.css (v4 @theme), tailwind.preset.js (v3),
tokens.dtcg.json (W3C design tokens) and tokens.ts.

Usage: python3 build_tokens.py <brand.json> <out_dir> [--self-hosted-fonts]

--self-hosted-fonts: leave out the Google Fonts @import (use scripts/fetch_fonts.py and link fonts.css).
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import brandlib as B  # noqa: E402


def main():
    args = [x for x in sys.argv[1:] if not x.startswith("--")]
    if len(args) != 2:
        sys.exit(__doc__)
    sys.argv[1:3] = args
    brand = B.load(sys.argv[1])
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)

    try:
        modes = B.modes(brand)
        pal = B.palette_hex(brand)
    except ValueError as e:
        sys.exit(f"colour error: {e}")

    t = brand.get("type", {})
    fams = t.get("families", {})
    scale = B.type_scale(brand)
    base = float(t.get("base", 16))
    leading = t.get("leading", {"tight": 1.1, "snug": 1.3, "body": 1.6})
    tracking = t.get("tracking", {})
    space = B.space_scale(brand)
    radius = brand.get("radius", {"none": 0, "sm": 4, "md": 8, "lg": 16, "pill": 999})
    elev = brand.get("elevation", {})
    motion = brand.get("motion", {})
    dur = motion.get("duration", {"fast": 150, "base": 250, "slow": 400})
    ease = motion.get("easing", {"standard": "cubic-bezier(.2,0,0,1)"})
    layout = brand.get("layout", {})
    bw = brand.get("border", {}).get("width", 1)

    def size_value(name, px):
        return B.fluid(px, base) if px >= base * 2.2 else f"{px / 16:.4g}rem"

    # ---------- tokens.css ----------
    L = ["/* Generated by heypip/build_tokens.py from brand.json — do not edit by hand. */"]
    url = None if "--self-hosted-fonts" in sys.argv else B.google_fonts_url(brand)
    if url:
        L.append(f"@import url(\"{url}\");")
    L.append(":root {")
    for k, v in pal.items():
        L.append(f"  --palette-{B.kebab(k)}: {v};")
    for role, v in modes["light"].items():
        L.append(f"  --color-{B.kebab(role)}: {v};")
    for k, fam in fams.items():
        L.append(f"  --font-{B.kebab(k)}: {B.font_stack(fam)};")
    for k, px in scale.items():
        L.append(f"  --text-{k}: {size_value(k, px)};")
    for k, v in leading.items():
        L.append(f"  --leading-{k}: {v};")
    for k, v in tracking.items():
        L.append(f"  --tracking-{k}: {v};")
    for k, px in space.items():
        L.append(f"  --space-{k}: {px / 16:.4g}rem;")
    for k, v in radius.items():
        L.append(f"  --radius-{k}: {v}px;")
    for k, v in elev.items():
        L.append(f"  --shadow-{k}: {v};")
    for k, v in dur.items():
        L.append(f"  --duration-{k}: {v}ms;")
    for k, v in ease.items():
        L.append(f"  --ease-{k}: {v};")
    L.append(f"  --border-width: {bw}px;")
    if layout.get("maxWidth"):
        L.append(f"  --layout-max: {layout['maxWidth']}px;")
    if layout.get("gutter") is not None:
        L.append(f"  --layout-gutter: {layout['gutter']}px;")
    if layout.get("margin") is not None:
        L.append(f"  --layout-margin: {layout['margin']}px;")
    L.append("  color-scheme: light;")
    L.append("}")
    if "dark" in modes:
        dark_vars = "\n".join(f"  --color-{B.kebab(r)}: {v};" for r, v in modes["dark"].items())
        L.append(f"[data-theme=\"dark\"] {{\n{dark_vars}\n  color-scheme: dark;\n}}")
        L.append(f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n{dark_vars.replace('  --', '    --')}\n    color-scheme: dark;\n  }}\n}}")
    L.append("@media (prefers-reduced-motion: reduce) {\n  :root {")
    for k in dur:
        L.append(f"    --duration-{k}: 1ms;")
    L.append("  }\n}")
    (out / "tokens.css").write_text("\n".join(L) + "\n", encoding="utf-8")

    # ---------- Tailwind v4 @theme (self-contained: real values, dark overrides below) ----------
    T = ["/* Generated by heypip/build_tokens.py. In your CSS: @import \"tailwindcss\"; @import \"./tokens.tailwind.css\"; */"]
    if url:
        T.insert(0, f"@import url(\"{url}\");")
    T.append("@theme {")
    for role, v in modes["light"].items():
        T.append(f"  --color-{B.kebab(role)}: {v};")
    for k, fam in fams.items():
        T.append(f"  --font-{B.kebab(k)}: {B.font_stack(fam)};")
    for k, px in scale.items():
        T.append(f"  --text-{k}: {size_value(k, px)};")
    for k, v in leading.items():
        T.append(f"  --leading-{k}: {v};")
    for k, v in radius.items():
        T.append(f"  --radius-{k}: {v}px;")
    for k, v in elev.items():
        if v != "none":
            T.append(f"  --shadow-{k}: {v};")
    for k, v in ease.items():
        T.append(f"  --ease-{k}: {v};")
    sb = brand.get("space", {}).get("base", 4)
    T.append(f"  --spacing: {sb / 16:.4g}rem;")
    if layout.get("maxWidth"):
        T.append(f"  --container-layout: {layout['maxWidth']}px;")
    T.append("}")
    if "dark" in modes:
        dv = "\n".join(f"  --color-{B.kebab(r)}: {v};" for r, v in modes["dark"].items())
        T.append(f"[data-theme=\"dark\"] {{\n{dv}\n}}")
        T.append(f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n{dv.replace('  --', '    --')}\n  }}\n}}")
    (out / "tokens.tailwind.css").write_text("\n".join(T) + "\n", encoding="utf-8")

    # ---------- Tailwind v3 preset ----------
    preset = {
        "theme": {
            "extend": {
                "colors": {B.kebab(r): f"var(--color-{B.kebab(r)})" for r in modes["light"]},
                "fontFamily": {B.kebab(k): [f"var(--font-{B.kebab(k)})"] for k in fams},
                "fontSize": {k: f"var(--text-{k})" for k in scale},
                "spacing": {k: f"var(--space-{k})" for k in space},
                "borderRadius": {k: f"var(--radius-{k})" for k in radius},
                "boxShadow": {k: f"var(--shadow-{k})" for k in elev},
                "transitionDuration": {k: f"var(--duration-{k})" for k in dur},
                "transitionTimingFunction": {k: f"var(--ease-{k})" for k in ease},
                "maxWidth": {"layout": "var(--layout-max)"} if layout.get("maxWidth") else {},
            }
        }
    }
    (out / "tailwind.preset.js").write_text(
        "// Generated by heypip/build_tokens.py. Import tokens.css in your global CSS.\nmodule.exports = "
        + json.dumps(preset, indent=2) + ";\n", encoding="utf-8")

    # ---------- W3C DTCG ----------
    def tok(v, t):
        return {"$value": v, "$type": t}
    dtcg = {
        "palette": {k: tok(v, "color") for k, v in pal.items()},
        "color": {m: {r: tok(v, "color") for r, v in roles.items()} for m, roles in modes.items()},
        "font": {k: tok([fam.get("name")] + [f.strip().strip("'\"") for f in fam.get("fallback", "").split(",") if f.strip()], "fontFamily") for k, fam in fams.items()},
        "fontSize": {k: tok(f"{px}px", "dimension") for k, px in scale.items()},
        "lineHeight": {k: tok(v, "number") for k, v in leading.items()},
        "space": {k: tok(f"{px}px", "dimension") for k, px in space.items()},
        "radius": {k: tok(f"{v}px", "dimension") for k, v in radius.items()},
        "shadow": {k: {"$value": v, "$type": "shadow"} for k, v in elev.items()},
        "duration": {k: tok(f"{v}ms", "duration") for k, v in dur.items()},
        "easing": {k: tok(v, "cubicBezier") for k, v in ease.items()},
    }
    (out / "tokens.dtcg.json").write_text(json.dumps(dtcg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    # ---------- TypeScript ----------
    ts = {
        "name": brand.get("name"),
        "color": modes,
        "palette": pal,
        "font": {k: B.font_stack(f) for k, f in fams.items()},
        "fontSize": scale,
        "leading": leading,
        "space": space,
        "radius": radius,
        "shadow": elev,
        "duration": dur,
        "easing": ease,
        "layout": layout,
    }
    (out / "tokens.ts").write_text("// Generated by heypip/build_tokens.py\nexport const tokens = "
                                   + json.dumps(ts, indent=2, ensure_ascii=False) + " as const;\nexport default tokens;\n",
                                   encoding="utf-8")

    files = ["tokens.css", "tokens.tailwind.css", "tailwind.preset.js", "tokens.dtcg.json", "tokens.ts"]
    print(f"wrote {len(files)} files to {out}: " + ", ".join(files))
    print(f"type scale (px): " + ", ".join(f"{k}={v:g}" for k, v in scale.items()))


if __name__ == "__main__":
    main()
